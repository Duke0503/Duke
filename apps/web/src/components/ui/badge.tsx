import * as React from "react";
import { cva, type VariantProps } from "class-variance-authority";
import { cn } from "cn";

const badgeVariants = cva(
  "inline-flex w-fit shrink-0 items-center gap-1 rounded-full border px-2 py-0.5 text-[11px] font-medium whitespace-nowrap",
  {
    variants: {
      variant: {
        default: "border-border bg-duke-card-2 text-muted-foreground",
        accent: "border-transparent bg-primary/15 text-primary",
        ember: "border-transparent bg-duke-ember/15 text-duke-ember",
        sage: "border-transparent bg-duke-sage/15 text-duke-sage",
        danger: "border-transparent bg-duke-danger/15 text-duke-danger",
        outline: "border-border text-foreground",
      },
    },
    defaultVariants: { variant: "default" },
  },
);

function Badge({
  className,
  variant,
  ...props
}: React.ComponentProps<"span"> & VariantProps<typeof badgeVariants>) {
  return <span data-slot="badge" className={cn(badgeVariants({ variant }), className)} {...props} />;
}

export { Badge, badgeVariants };
